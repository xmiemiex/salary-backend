const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({ headless: true, channel: 'msedge' });
 const context = await browser.newContext({ viewport: { width: 2560, height: 1440 } });
 const page = await context.newPage();
 const failures = []; page.on('pageerror', error => failures.push(error.message));
 const login = JSON.parse(fs.readFileSync('tmp/monthly-finance/login.json', 'utf8'));
 await page.goto('http://localhost:5189');
 await page.getByLabel('用户名').fill(login.username); await page.getByLabel('密码', { exact: true }).fill(login.password);
 await page.getByRole('button', { name: /登\s*录/ }).click();
 await expect(page.getByRole('heading', { name: '月度收支' })).toBeVisible();
 await expect(page.getByRole('button', { name: 'SUB-001', exact: true })).toBeVisible();
 await page.screenshot({ path: 'tmp/monthly-finance/01-missing-fees.png', fullPage: true, animations: 'disabled' });
 await page.getByRole('button', { name: '本月手续费', exact: true }).click();
 const fields = page.locator('.ant-drawer input');
 await fields.nth(0).fill('3'); await fields.nth(1).fill('5'); await fields.nth(2).fill('2');
 await page.screenshot({ path: 'tmp/monthly-finance/02-fees.png', fullPage: true, animations: 'disabled' });
 await page.getByRole('button', { name: '保存本月费率', exact: true }).click();
 await expect(page.locator('.ant-drawer')).toHaveCount(0);
 await page.getByRole('button', { name: /编\s*辑/ }).click();
 await page.locator('.ant-drawer input').fill('1000');
 await page.screenshot({ path: 'tmp/monthly-finance/03-adpos.png', fullPage: true, animations: 'disabled' });
 await page.getByRole('button', { name: '保存花费', exact: true }).click(); await expect(page.locator('.ant-drawer')).toHaveCount(0);
 await expect(page.getByText('140.96%', { exact: true }).first()).toBeVisible();
 await page.screenshot({ path: 'tmp/monthly-finance/04-dashboard.png', fullPage: true, animations: 'disabled' });
 await page.getByRole('button', { name: '刷新数据', exact: true }).click();
 await expect(page.getByText('刷新失败', { exact: true }).first()).toBeVisible();
 await expect(page.getByText('140.96%', { exact: true }).first()).toBeVisible();
 await page.screenshot({ path: 'tmp/monthly-finance/05-failure.png', fullPage: true, animations: 'disabled' });
 await page.reload(); await expect(page.getByText('刷新失败', { exact: true }).first()).toBeVisible();
 await expect(page.getByText('140.96%', { exact: true }).first()).toBeVisible();
 await page.getByRole('button', { name: 'SUB-001', exact: true }).click();
 await expect(page.getByText('原始联盟 SUB ID：original-0、original-1、original-2')).toBeVisible();
 await page.screenshot({ path: 'tmp/monthly-finance/06-details.png', fullPage: true, animations: 'disabled' });
 await context.storageState({ path: 'tmp/monthly-finance/browser-state.json' });
 if (failures.length) throw new Error(failures.join('\n'));
 console.log('Browser PASS: login, unified SUB row, fee save, Adpos save, exact sample margin, failed refresh retains manual input and amounts, reload restores source status, source drawer. Third-party data is a local fixture.');
 await browser.close();
})().catch(e => { console.error(e.message); process.exit(1); });
